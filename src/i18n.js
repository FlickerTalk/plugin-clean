export const LANGUAGES = Object.keys(CATALOGUE);

/** The catalogue for a language tag: exact, then its base (`pt-BR` → `pt`), then English. */
export function catalogueOf(lang) {
  const tag = String(lang ?? "en");
  return CATALOGUE[tag] ?? CATALOGUE[tag.split("-")[0]] ?? CATALOGUE.en;
}

/** A text in the language of the phone (English if it lacks it), with `{name}`s filled in. */
export function t(lang, key, fill = {}) {
  const text = catalogueOf(lang)[key] ?? CATALOGUE.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (whole, name) => (name in fill ? String(fill[name]) : whole));
}

/** Which way the language is written: Arabic right to left. */
export function directionOf(lang) {
  return String(lang ?? "").split("-")[0] === "ar" ? "rtl" : "ltr";
}
